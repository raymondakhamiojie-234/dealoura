'use client'

import { useState } from 'react'
import Link from 'next/link'
import { Copy, Check, Share2, Users, Wallet, TrendingUp } from 'lucide-react'

interface ReferralDashboardClientProps {
  username: string
  referralLink: string
  walletBalance: number
}

export function ReferralDashboardClient({
  username,
  referralLink,
  walletBalance
}: ReferralDashboardClientProps) {
  const [copied, setCopied] = useState(false)

  const handleCopy = () => {
    navigator.clipboard.writeText(referralLink)
    setCopied(true)
    setTimeout(() => setCopied(false), 2000)
  }

  const tweetText = encodeURIComponent(
    `I use Dealoura to buy and sell verified social media accounts with 100% middleman escrow protection. Check it out: ${referralLink}`
  )

  const telegramText = encodeURIComponent(
    `Dealoura — The premier escrow marketplace for verified social media accounts and channels: ${referralLink}`
  )

  const whatsappText = encodeURIComponent(
    `Buy and sell verified social media accounts safely on Dealoura: ${referralLink}`
  )

  return (
    <div className="space-y-6">
      
      {/* Referral Link & Share Box */}
      <div className="rounded-3xl bg-[#010b13] p-6 sm:p-8 text-[#ebf1f5] border border-[#0a1722] shadow-xl space-y-6">
        <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4">
          <div>
            <span className="text-[10px] font-mono font-bold tracking-wider uppercase px-2.5 py-0.5 rounded-full bg-[#ebf1f5]/10 text-[#ebf1f5] border border-[#ebf1f5]/20">
              Partner Dashboard
            </span>
            <h2 className="text-xl sm:text-2xl font-black text-white mt-1">
              Your Personalized Referral Link
            </h2>
            <p className="text-xs text-[#ebf1f5]/70 mt-0.5">
              Share this link to earn 20% on all escrow fees generated by your referrals.
            </p>
          </div>

          <div className="text-left sm:text-right">
            <span className="text-[10px] font-mono uppercase text-[#ebf1f5]/60 block">Available in Wallet</span>
            <div className="flex items-center gap-2">
              <span className="text-xl font-black text-white font-mono">
                ${walletBalance.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}
              </span>
              <Link
                href="/dashboard/wallet"
                className="text-[11px] font-bold text-[#ebf1f5] hover:underline"
              >
                Withdraw
              </Link>
            </div>
          </div>
        </div>

        {/* Link Input & Copy */}
        <div className="flex flex-col sm:flex-row gap-2.5">
          <div className="flex-1 bg-[#071520] p-3.5 rounded-2xl border border-[#0f2436] font-mono text-xs text-[#ebf1f5] select-all truncate">
            {referralLink}
          </div>
          <button
            type="button"
            onClick={handleCopy}
            className="py-3.5 px-6 rounded-2xl bg-[#ebf1f5] hover:bg-white text-[#010b13] font-bold text-xs shadow-md transition flex items-center justify-center gap-2 cursor-pointer shrink-0"
          >
            {copied ? (
              <>
                <Check className="w-4 h-4 text-[#010b13]" />
                <span>Copied to Clipboard!</span>
              </>
            ) : (
              <>
                <Copy className="w-4 h-4 text-[#010b13]" />
                <span>Copy Referral Link</span>
              </>
            )}
          </button>
        </div>

        {/* Social Share Buttons */}
        <div className="pt-2 flex flex-wrap items-center gap-2.5 text-xs">
          <span className="text-[#ebf1f5]/60 text-[11px] font-mono mr-1">Quick Share:</span>
          <a
            href={`https://twitter.com/intent/tweet?text=${tweetText}`}
            target="_blank"
            rel="noopener noreferrer"
            className="px-3.5 py-1.5 rounded-xl bg-[#071520] hover:bg-[#0f2436] text-[#ebf1f5] font-bold transition flex items-center gap-1.5 border border-[#0f2436]"
          >
            <span className="font-black">𝕏</span> Share on X
          </a>
          <a
            href={`https://t.me/share/url?url=${referralLink}&text=${telegramText}`}
            target="_blank"
            rel="noopener noreferrer"
            className="px-3.5 py-1.5 rounded-xl bg-[#071520] hover:bg-[#0f2436] text-[#ebf1f5] font-bold transition flex items-center gap-1.5 border border-[#0f2436]"
          >
            Telegram
          </a>
          <a
            href={`https://api.whatsapp.com/send?text=${whatsappText}`}
            target="_blank"
            rel="noopener noreferrer"
            className="px-3.5 py-1.5 rounded-xl bg-[#071520] hover:bg-[#0f2436] text-[#ebf1f5] font-bold transition flex items-center gap-1.5 border border-[#0f2436]"
          >
            WhatsApp
          </a>
        </div>
      </div>

      {/* Real-time Metric Cards */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-6">
        <div className="bg-white p-6 rounded-3xl border border-[#d2dde4] shadow-xs">
          <div className="flex items-center justify-between mb-2">
            <span className="text-[11px] font-mono font-bold text-[#526371] uppercase">Referral Rate</span>
            <TrendingUp className="w-4 h-4 text-[#010b13]" />
          </div>
          <span className="text-3xl font-black text-[#010b13] font-mono">20%</span>
          <p className="text-xs text-[#526371] mt-1">Of all escrow transaction fees</p>
        </div>

        <div className="bg-white p-6 rounded-3xl border border-[#d2dde4] shadow-xs">
          <div className="flex items-center justify-between mb-2">
            <span className="text-[11px] font-mono font-bold text-[#526371] uppercase">Cookie Window</span>
            <Users className="w-4 h-4 text-[#010b13]" />
          </div>
          <span className="text-3xl font-black text-[#010b13] font-mono">90 Days</span>
          <p className="text-xs text-[#526371] mt-1">Lifetime attribution on sign up</p>
        </div>

        <div className="bg-white p-6 rounded-3xl border border-[#d2dde4] shadow-xs">
          <div className="flex items-center justify-between mb-2">
            <span className="text-[11px] font-mono font-bold text-[#526371] uppercase">Payout Destination</span>
            <Wallet className="w-4 h-4 text-[#010b13]" />
          </div>
          <span className="text-xl font-black text-[#010b13] block mt-1">Dealoura Wallet</span>
          <p className="text-xs text-[#526371] mt-1">Auto-credited upon escrow close</p>
        </div>
      </div>

    </div>
  )
}
