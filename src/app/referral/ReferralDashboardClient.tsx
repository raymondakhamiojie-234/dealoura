'use client'

import { useState } from 'react'
import Link from 'next/link'
import { Copy, Check, Share2, Users, DollarSign, Wallet, ArrowUpRight, TrendingUp } from 'lucide-react'

interface ReferralDashboardClientProps {
  username: string
  referralLink: string
  walletBalance: number
}

export function ReferralDashboardClient({
  username,
  referralLink,
  walletBalance
}: ReferralDashboardClientProps) {
  const [copied, setCopied] = useState(false)

  const handleCopy = () => {
    navigator.clipboard.writeText(referralLink)
    setCopied(true)
    setTimeout(() => setCopied(false), 2000)
  }

  const tweetText = encodeURIComponent(
    `I use Dealoura to buy and sell verified social media accounts with 100% middleman escrow protection. Check it out: ${referralLink}`
  )

  const telegramText = encodeURIComponent(
    `Dealoura — The premier escrow marketplace for verified social media accounts and channels: ${referralLink}`
  )

  const whatsappText = encodeURIComponent(
    `Buy and sell verified social media accounts safely on Dealoura: ${referralLink}`
  )

  return (
    <div className="space-y-6">
      
      {/* Referral Link & Share Box */}
      <div className="rounded-3xl bg-gradient-to-br from-slate-900 via-slate-900 to-blue-950 p-6 sm:p-8 text-white border border-slate-800 shadow-xl space-y-6">
        <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4">
          <div>
            <span className="text-[10px] font-mono font-bold tracking-wider uppercase px-2.5 py-0.5 rounded-full bg-blue-500/20 text-blue-400 border border-blue-500/30">
              Partner Dashboard
            </span>
            <h2 className="text-xl sm:text-2xl font-black text-white mt-1">
              Your Personalized Referral Link
            </h2>
            <p className="text-xs text-slate-400 mt-0.5">
              Share this link to earn 20% on all escrow fees generated by your referrals.
            </p>
          </div>

          <div className="text-left sm:text-right">
            <span className="text-[10px] font-mono uppercase text-slate-400 block">Available in Wallet</span>
            <div className="flex items-center gap-2">
              <span className="text-xl font-black text-emerald-400 font-mono">
                ${walletBalance.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}
              </span>
              <Link
                href="/dashboard/wallet"
                className="text-[11px] font-bold text-blue-400 hover:text-blue-300 underline"
              >
                Withdraw
              </Link>
            </div>
          </div>
        </div>

        {/* Link Input & Copy */}
        <div className="flex flex-col sm:flex-row gap-2.5">
          <div className="flex-1 bg-slate-950 p-3.5 rounded-2xl border border-slate-800 font-mono text-xs text-slate-200 select-all truncate">
            {referralLink}
          </div>
          <button
            type="button"
            onClick={handleCopy}
            className="py-3.5 px-6 rounded-2xl bg-blue-600 hover:bg-blue-500 text-white font-bold text-xs shadow-md shadow-blue-500/20 transition flex items-center justify-center gap-2 cursor-pointer shrink-0"
          >
            {copied ? (
              <>
                <Check className="w-4 h-4 text-emerald-300" />
                <span>Copied to Clipboard!</span>
              </>
            ) : (
              <>
                <Copy className="w-4 h-4" />
                <span>Copy Referral Link</span>
              </>
            )}
          </button>
        </div>

        {/* Social Share Buttons */}
        <div className="pt-2 flex flex-wrap items-center gap-2.5 text-xs">
          <span className="text-slate-400 text-[11px] font-mono mr-1">Quick Share:</span>
          <a
            href={`https://twitter.com/intent/tweet?text=${tweetText}`}
            target="_blank"
            rel="noopener noreferrer"
            className="px-3.5 py-1.5 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-200 font-bold transition flex items-center gap-1.5"
          >
            <span className="font-black">𝕏</span> Share on X
          </a>
          <a
            href={`https://t.me/share/url?url=${referralLink}&text=${telegramText}`}
            target="_blank"
            rel="noopener noreferrer"
            className="px-3.5 py-1.5 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-200 font-bold transition flex items-center gap-1.5"
          >
            Telegram
          </a>
          <a
            href={`https://api.whatsapp.com/send?text=${whatsappText}`}
            target="_blank"
            rel="noopener noreferrer"
            className="px-3.5 py-1.5 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-200 font-bold transition flex items-center gap-1.5"
          >
            WhatsApp
          </a>
        </div>
      </div>

      {/* Real-time Metric Cards */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-6">
        <div className="bg-white p-6 rounded-3xl border border-slate-200 shadow-xs">
          <div className="flex items-center justify-between mb-2">
            <span className="text-[11px] font-mono font-bold text-slate-400 uppercase">Referral Rate</span>
            <TrendingUp className="w-4 h-4 text-blue-600" />
          </div>
          <span className="text-3xl font-black text-slate-900 font-mono">20%</span>
          <p className="text-xs text-slate-500 mt-1">Of all escrow transaction fees</p>
        </div>

        <div className="bg-white p-6 rounded-3xl border border-slate-200 shadow-xs">
          <div className="flex items-center justify-between mb-2">
            <span className="text-[11px] font-mono font-bold text-slate-400 uppercase">Cookie Window</span>
            <Users className="w-4 h-4 text-emerald-600" />
          </div>
          <span className="text-3xl font-black text-slate-900 font-mono">90 Days</span>
          <p className="text-xs text-slate-500 mt-1">Lifetime attribution on sign up</p>
        </div>

        <div className="bg-white p-6 rounded-3xl border border-slate-200 shadow-xs">
          <div className="flex items-center justify-between mb-2">
            <span className="text-[11px] font-mono font-bold text-slate-400 uppercase">Payout Destination</span>
            <Wallet className="w-4 h-4 text-purple-600" />
          </div>
          <span className="text-xl font-black text-slate-900 block mt-1">Dealoura Wallet</span>
          <p className="text-xs text-slate-500 mt-1">Auto-credited upon escrow close</p>
        </div>
      </div>

    </div>
  )
}
